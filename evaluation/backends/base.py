"""
Base interface and dataclasses for Judge backends.
"""

from __future__ import annotations

import abc
from dataclasses import dataclass
from typing import Any, Dict, List, Optional


@dataclass
class BackendPricing:
    """Pricing configuration per 1k tokens in USD."""
    prompt_per_1k: float = 0.0
    completion_per_1k: float = 0.0

    def estimate_cost(self, prompt_tokens: int, completion_tokens: int) -> float:
        return (
            (prompt_tokens / 1000.0) * self.prompt_per_1k
            + (completion_tokens / 1000.0) * self.completion_per_1k
        )


class JudgeBackend(abc.ABC):
    """Abstract base class for all LLM judge inference backends."""

    def __init__(
        self,
        model_name: str,
        pricing: Optional[BackendPricing] = None,
        **kwargs: Any,
    ):
        self.model_name = model_name
        self.pricing = pricing or BackendPricing()
        self.extra_config = kwargs

    @property
    @abc.abstractmethod
    def backend_type(self) -> str:
        """Name or identifier of the backend type (e.g., 'groq', 'openai_compatible', 'mock')."""
        pass

    @abc.abstractmethod
    def generate_judgment(
        self,
        messages: List[Dict[str, str]],
        temperature: float = 0.1,
        json_mode: bool = True,
        max_tokens: Optional[int] = None,
    ) -> str:
        """
        Executes a completion request given chat messages.

        Args:
            messages: List of chat messages with 'role' and 'content'.
            temperature: Sampling temperature.
            json_mode: Whether to instruct backend to force valid JSON output.
            max_tokens: Maximum output tokens.

        Returns:
            The raw string response generated by the LLM.
        """
        pass
